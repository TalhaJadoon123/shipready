import type { GenerateResult, GeneratedDocument } from './generate.js';
import { findGaps, sortGaps, complianceScore, type ComplianceAnswer, type Gap } from './types.js';

/**
 * Export formats.
 *
 * Three, because three is what people actually need:
 *
 *  - **markdown** — the working format, diffable, readable in a PR;
 *  - **json** — for the dashboard and for re-rendering;
 *  - **docx** — for the lawyer or accountant who will not open a .md file.
 *
 * DOCX is emitted as a minimal OOXML package rather than through a document
 * library: a compliance pack is plain paragraphs and tables, and a 200 kB
 * dependency that renders headings differently from Word is not worth it. The
 * output opens in Word, LibreOffice and Google Docs.
 */
export type ExportFormat = 'md' | 'markdown' | 'json' | 'docx';

export interface BundleFile {
  /** Path relative to the output directory. */
  path: string;
  content: string | Uint8Array;
  kind: 'markdown' | 'json' | 'document';
  title: string;
  framework: string;
}

export interface BundleResult {
  format: ExportFormat;
  files: BundleFile[];
  /** The manifest describing what was generated and what is missing. */
  manifest: BundleManifest;
}

export interface BundleManifest {
  company: string;
  system: string;
  generatedAt: string;
  frameworks: string[];
  documentCount: number;
  gapCount: number;
  blockers: number;
  score: number;
  gaps: Gap[];
  documents: { id: string; title: string; reference: string; path: string; unresolved: string[] }[];
  disclaimer: string;
}

const DISCLAIMER =
  'Generated by ShipReady from a self-assessment. These documents are a starting point for your compliance work, not legal advice, not a conformity assessment, and not a substitute for professional review. Verify every statement against your actual operations before relying on it.';

/** Build the manifest describing a generated pack. */
export function buildManifest(answer: ComplianceAnswer, result: GenerateResult): BundleManifest {
  const gaps = result.gaps.length > 0 ? result.gaps : sortGaps(findGaps(answer));
  return {
    company: answer.company.legalName,
    system: answer.aiSystem.name,
    generatedAt: result.generatedAt,
    frameworks: result.frameworks,
    documentCount: result.documents.length,
    gapCount: gaps.length,
    blockers: gaps.filter((g) => g.severity === 'blocker').length,
    score: result.score > 0 ? result.score : complianceScore(gaps),
    gaps,
    documents: result.documents.map((doc) => ({
      id: doc.id,
      title: doc.title,
      reference: doc.reference,
      path: doc.id.replace('/', '/') + '.md',
      unresolved: doc.unresolved,
    })),
    disclaimer: DISCLAIMER,
  };
}

/** One markdown file per document, plus a manifest and a README index. */
export function toMarkdownBundle(result: GenerateResult, manifest: BundleManifest): BundleResult {
  const files: BundleFile[] = [];

  for (const document of result.documents) {
    files.push({
      path: `${document.framework}/${document.id.split('/')[1] ?? document.id}.md`,
      content: withHeader(document),
      kind: 'markdown',
      title: document.title,
      framework: document.framework,
    });
  }

  files.push({
    path: 'MANIFEST.md',
    content: renderManifestMarkdown(manifest),
    kind: 'markdown',
    title: 'Compliance manifest',
    framework: 'all',
  });

  files.push({
    path: 'README.md',
    content: renderIndexMarkdown(manifest, result.documents),
    kind: 'markdown',
    title: 'Compliance pack index',
    framework: 'all',
  });

  return { format: 'md', files, manifest };
}

/** A single JSON document containing everything. */
export function toJsonBundle(result: GenerateResult, manifest: BundleManifest): BundleResult {
  const content = JSON.stringify(
    {
      manifest,
      documents: result.documents.map((d) => ({
        id: d.id,
        framework: d.framework,
        title: d.title,
        reference: d.reference,
        markdown: d.content,
        gaps: d.gaps,
        unresolvedPlaceholders: d.unresolved,
      })),
    },
    null,
    2,
  );
  return {
    format: 'json',
    files: [{ path: 'compliance-pack.json', content, kind: 'json', title: 'Compliance pack', framework: 'all' }],
    manifest,
  };
}

/**
 * DOCX bundle: one document containing every section.
 *
 * Word supports a multi-page document far better than it supports opening many
 * files, so the pack ships as a single `.docx` with a table of contents field.
 */
export function toDocxBundle(result: GenerateResult, manifest: BundleManifest): BundleResult {
  const body = renderDocxBody(result.documents, manifest);
  return {
    format: 'docx',
    files: [
      { path: 'compliance-pack.docx', content: buildDocx(body), kind: 'document', title: 'Compliance pack', framework: 'all' },
    ],
    manifest,
  };
}

