function withHeader(document: GeneratedDocument): string {
  return [
    `<!-- Framework: ${document.framework} -->`,
    `<!-- Reference: ${document.reference} -->`,
    `<!-- Gaps affecting this document: ${document.gaps.length} -->`,
    '',
    document.content,
  ].join('\n');
}

function renderManifestMarkdown(manifest: BundleManifest): string {
  const lines: string[] = [];
  lines.push('# Compliance manifest');
  lines.push('');
  lines.push(`**Company:** ${manifest.company}`);
  lines.push(`**System:** ${manifest.system}`);
  lines.push(`**Generated:** ${manifest.generatedAt}`);
  lines.push(`**Readiness score:** ${manifest.score}/100`);
  lines.push('');
  lines.push(`This pack contains ${manifest.documentCount} documents across ${manifest.frameworks.join(', ')}.`);
  lines.push('');

  lines.push('## Documents');
  lines.push('');
  lines.push('| Document | Reference | Unresolved placeholders |');
  lines.push('| --- | --- | --- |');
  for (const doc of manifest.documents) {
    lines.push(`| ${doc.title} | ${doc.reference} | ${doc.unresolved.length === 0 ? 'none' : doc.unresolved.length} |`);
  }
  lines.push('');

  lines.push('## Gaps');
  lines.push('');
  if (manifest.gaps.length === 0) {
    lines.push('No gaps were identified from the answers provided.');
  } else {
    lines.push('| Severity | Missing | Why it matters |');
    lines.push('| --- | --- | --- |');
    for (const gap of manifest.gaps) {
      lines.push(`| ${gap.severity.toUpperCase()} | ${escapeCell(gap.message)} | ${escapeCell(gap.why)} |`);
    }
  }
  lines.push('');
  lines.push('## Disclaimer');
  lines.push('');
  lines.push(manifest.disclaimer);
  lines.push('');
  return lines.join('\n');
}

function renderIndexMarkdown(manifest: BundleManifest, documents: readonly GeneratedDocument[]): string {
  const lines: string[] = [];
  lines.push(`# ${manifest.company} — compliance pack`);
  lines.push('');
  lines.push(`System: **${manifest.system}**  |  Generated: ${manifest.generatedAt}  |  Readiness: **${manifest.score}/100**`);
  lines.push('');
  lines.push('## What is in here');
  lines.push('');
  for (const framework of manifest.frameworks) {
    lines.push(`### ${framework.toUpperCase()}`);
    lines.push('');
    for (const document of documents.filter((d) => d.framework === framework)) {
      const gapCount = document.gaps.length;
      lines.push(
        `- [${document.title}](./${framework}/${document.id.split('/')[1] ?? document.id}.md) — ${document.reference}${gapCount > 0 ? ` · **${gapCount} gap(s)**` : ''}`,
      );
    }
    lines.push('');
  }

  if (manifest.blockers > 0) {
    lines.push('---');
    lines.push('');
    lines.push(`> **${manifest.blockers} blocker(s) before launch.** See [MANIFEST.md](./MANIFEST.md).`);
    lines.push('');
  }

  lines.push('## How to use this pack');
  lines.push('');
  lines.push('1. Read `MANIFEST.md` first. It lists what is missing and why it matters.');
  lines.push('2. Work the blockers, in order. A blocker means the document is not merely incomplete.');
  lines.push('3. Fill every `**NOT PROVIDED**` marker. Each one is a question a regulator can ask.');
  lines.push('4. Have a qualified person review before relying on any of it.');
  lines.push('');
  lines.push(manifest.disclaimer);
  lines.push('');
  return lines.join('\n');
}

function escapeCell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

